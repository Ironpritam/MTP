# experiments/run_experiment.py
import pandas as pd
from gui.data_loader import DataLoader
from gui.model_training import ModelTraining
from utils.data_preprocessing import preprocess_data
from utils.model_utils import save_model, load_model
from utils.environment import EnhancedSensorEnv
from models.ppo_model import create_ppo_model

def run_experiment(data_file):
    # Load data
    data_loader = DataLoader()
    data_loader.load_data(data_file)

    # Preprocess data
    data, scaler = preprocess_data(data_loader.data)

    # Setup environment
    env = EnhancedSensorEnv(data)

    # Create and train PPO model
    model = create_ppo_model(env)
    model.learn(total_timesteps=10000)

    # Save the model
    save_model(model, "ppo_model.pkl")

    # Test the model
    predictions = test_model(model, data_loader.data)
    print(predictions)

def test_model(model, real_time_data):
    """
    Test the trained model on real-time data.

    :param model: The trained PPO model
    :param real_time_data: The real-time sensor data
    :return: The predictions generated by the model
    """
    predictions = []
    obs = real_time_data.iloc[:model.env.history_length].values  # Initialize with history length
    for i in range(model.env.history_length, len(real_time_data)):
        action, _ = model.predict(obs)
        predictions.append(action)
        obs = real_time_data.iloc[i - model.env.history_length:i].values  # Move window forward
    return predictions
